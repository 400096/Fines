USE `fine_management`;

ALTER TABLE `Departments`
    COMMENT = '部门信息表',
    MODIFY COLUMN `Id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '部门主键',
    MODIFY COLUMN `Name` VARCHAR(100) NOT NULL COMMENT '部门名称',
    MODIFY COLUMN `Code` VARCHAR(30) NOT NULL COMMENT '部门编码',
    MODIFY COLUMN `SortOrder` INT NOT NULL DEFAULT 0 COMMENT '显示排序，数值越小越靠前',
    MODIFY COLUMN `IsEnabled` TINYINT(1) NOT NULL DEFAULT 1 COMMENT '是否启用：1启用，0停用',
    MODIFY COLUMN `Manager` VARCHAR(50) NULL COMMENT '部门负责人',
    MODIFY COLUMN `Remark` VARCHAR(300) NULL COMMENT '备注',
    MODIFY COLUMN `CreatedAt` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间（UTC）',
    MODIFY COLUMN `UpdatedAt` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '最后更新时间（UTC）',
    MODIFY COLUMN `IsDeleted` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '逻辑删除标记：1已删除，0正常',
    MODIFY COLUMN `DeletedAt` DATETIME(6) NULL COMMENT '逻辑删除时间（UTC）';

